//! Differential test vectors: Python generated the expected values; Rust must match.
use koppa::{Ratio, compare, DeferredChain};
use num_bigint::BigInt;

#[test] fn negative_factors_match_python() {
    // Python: compose(1,-3)=-3.0, (-1,3)=-3.0, (-2,-3)=1.5, (2,-3)=-1.5
    for (a,b,exp) in [(1,-3,-3.0),(-1,3,-3.0),(-2,-3,1.5),(2,-3,-1.5)] {
        let mut c=DeferredChain::new();
        c.compose(&BigInt::from(a),&BigInt::from(b));
        assert!((c.resolve_float()-exp).abs()<1e-12, "compose({a},{b}) got {} want {exp}", c.resolve_float());
        let mut d=DeferredChain::new();
        d.compose_decimal(&BigInt::from(a),&BigInt::from(b));
        assert!((d.resolve_float()-exp).abs()<1e-12, "compose_decimal({a},{b}) got {} want {exp}", d.resolve_float());
    }
}

#[test] fn differential_compare_vectors() {
    // (a1,b1,a2,b2,expected) generated by Python's exact cross-product
    let v: Vec<(i64,i64,i64,i64,i32)> = vec![
        (1,2,2,4,0), (1,2,1,3,-1), (1,3,1,2,1),
        (7952614671698527,21159794283675467,5364900327947194,14274574083889309,-1),
        (10,3,20,7,-1), (10,3,100,30,0), (7,11,5,8,-1),
        (1000000,999999,1000001,1000000,-1),
        (-1,2,1,-2,0), (-1,2,-1,3,1),
    ];
    for (a1,b1,a2,b2,e) in v {
        let r1=Ratio::new(BigInt::from(a1),BigInt::from(b1));
        let r2=Ratio::new(BigInt::from(a2),BigInt::from(b2));
        assert_eq!(compare(&r1,&r2), e, "compare(({a1},{b1}),({a2},{b2}))");
    }
}
